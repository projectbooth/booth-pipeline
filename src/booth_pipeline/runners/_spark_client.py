"""Executed inside a Spark task's pod (ADR 0119; docs/design-spark-runner.md), never imported by the service.

The pod runs no user code: this module-owned client submits the task's saved PySpark code to booth-spark
through core's gateway, as the run (the pod's workload token), then polls the application until it ends,
copying its driver log to stdout and reporting its state as events on stderr. runners/spark.py, in the
API/scheduler pod, turns those events into the run's log lines and the attempt's Spark record, and is
the one that stops an application on cancel, timeout or a lost pod (this process may be killed outright).

Standard library only, under ``python -I``, like the harness.

    _spark_client.py WORKDIR RESULT_PATH

WORKDIR holds task.py (the task's code), invocation.json and the token file (BOOTH_TOKEN_FILE), which the
runner service replaces when the backend refreshes the token, so it is re-read on every request.
"""

from __future__ import annotations

import base64
import json
import os
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

EVENT = "BOOTH-SPARK-EVENT "  # stderr: one JSON event per line, read by runners/spark.py
OUTPUT = "BOOTH-PIPELINE-OUTPUT "  # the driver log's line carrying run(ctx)'s return value, or its ctx.skip
MAX_INLINE = 256 * 1024  # booth-spark's main.inlinePython limit
MAX_OUTPUT = 64 * 1024
TERMINAL = ("succeeded", "failed", "stopped")

# Runs inside the Spark driver: the task's code with a ctx, as the base runner gives one (README).
PRELUDE = '''\
# Generated by booth-pipeline (ADR 0119) around this task's saved code.
import base64 as _b64, json as _json, logging as _logging, sys as _sys
from pyspark.sql import SparkSession as _SparkSession

_BOOTH = _json.loads(%(booth)s)
_SOURCE = %(source)s


class _Trigger:
    def __init__(self, t):
        t = t or {}
        self.type = t.get("type") or "manual"
        self.events = list(t.get("events") or [])
        self.count = int(t.get("count") or 0)
        self.missed_events = bool(t.get("missedEvents"))
        self.scheduled_for = t.get("scheduledFor")
        self.scheduledFor = self.scheduled_for


class _Skipped(BaseException):
    pass


class _Ctx:
    def __init__(self, spark):
        self.spark = spark
        self.params = _BOOTH["params"]
        self.inputs = _BOOTH["inputs"]
        self.run_id = _BOOTH["runId"]
        self.task_key = _BOOTH["taskKey"]
        self.attempt = _BOOTH["attempt"]
        self.trigger = _Trigger(_BOOTH.get("trigger"))
        _logging.basicConfig(stream=_sys.stderr, level=_logging.INFO, format="%%(levelname)s %%(message)s")
        self.log = _logging.getLogger("task." + self.task_key)

    def skip(self, reason=""):
        raise _Skipped(str(reason or "skipped by the task"))


spark = _SparkSession.builder.getOrCreate()
if _BOOTH.get("modules"):
    # Shared modules from the catalog: importable in the driver, and shipped to the executors.
    import os as _os, tempfile as _tempfile
    _mods = _tempfile.mkdtemp(prefix="booth-modules-")
    for _name, _src in _BOOTH["modules"].items():
        _path = _os.path.join(_mods, _name + ".py")
        with open(_path, "w", encoding="utf-8") as _f:
            _f.write(_src)
        spark.sparkContext.addPyFile(_path)
    _sys.path.insert(0, _mods)
ctx = _Ctx(spark)
_sys.argv = ["task.py", *_BOOTH["args"]]
_ns = {"__name__": "__booth_task__", "spark": spark, "ctx": ctx}
exec(compile(_SOURCE, "task.py", "exec"), _ns)
try:
    _res = {"output": _ns["run"](ctx) if callable(_ns.get("run")) else None}
except _Skipped as _e:
    _res = {"output": None, "skipped": str(_e)[:1000]}
_enc = _json.dumps(_res)
if len(_enc.encode("utf-8")) > %(max_output)d:
    raise SystemExit("task output exceeds %(max_output)d bytes; pass data through the lakehouse, not through ctx")
print(%(marker)r + _b64.b64encode(_enc.encode("utf-8")).decode("ascii"), flush=True)
'''


class Failed(Exception):
    """The attempt fails with this message (written to failure.txt for the runner service)."""


def event(kind: str, **data: object) -> None:
    print(EVENT + json.dumps({"event": kind, **data}), file=sys.stderr, flush=True)


class Spark:
    def __init__(self, base: str, workspace: str, token_file: str) -> None:
        self.base = base.rstrip("/")
        self.workspace = workspace
        self.token_file = token_file

    def call(self, method: str, path: str, body: object = None, headers: dict[str, str] | None = None, timeout: float = 30) -> tuple[int, dict[str, str], bytes]:
        with open(self.token_file, encoding="utf-8") as f:
            token = f.read().strip()
        h = {"Authorization": f"Bearer {token}", "X-Workspace": self.workspace, **(headers or {})}
        data = None
        if body is not None:
            data = json.dumps(body).encode("utf-8")
            h["Content-Type"] = "application/json"
        req = urllib.request.Request(self.base + path, data=data, headers=h, method=method)
        try:
            with urllib.request.urlopen(req, timeout=timeout) as r:  # noqa: S310 - the gateway, from the chart
                return r.status, dict(r.headers), r.read()
        except urllib.error.HTTPError as e:
            return e.code, dict(e.headers or {}), e.read()


def spark_error(status: int, raw: bytes) -> str:
    try:
        body = json.loads(raw)
        msg = body.get("error") or body.get("detail") or ""
        code = body.get("code")
        return f"{msg} ({code})" if code and msg else str(msg or code or f"HTTP {status}")
    except (ValueError, AttributeError):
        return raw.decode("utf-8", errors="replace").strip()[:500] or f"HTTP {status}"


def build_code(source: str, inv: dict, spark: dict, modules: dict[str, str] | None = None) -> str:
    booth = {
        "modules": modules or {},
        "params": inv.get("params") or {},
        "inputs": inv.get("inputs") or {},
        "runId": inv["runId"],
        "taskKey": inv["taskKey"],
        "attempt": inv["attempt"],
        "args": list(spark.get("args") or []),
        "trigger": inv.get("trigger"),
    }
    code = PRELUDE % {"booth": repr(json.dumps(booth)), "source": repr(source), "max_output": MAX_OUTPUT, "marker": OUTPUT}
    if len(code.encode("utf-8")) > MAX_INLINE:
        raise Failed(
            f"this task's code, shared modules and inputs come to {len(code.encode('utf-8')) // 1024} KiB with the prelude, more than booth-spark's "
            "256 KiB; pass large inputs through the lakehouse instead of ctx.inputs"
        )
    return code


def app_name(inv: dict) -> str:
    raw = f"pipeline {inv['taskKey']} {inv['runId'][:8]} a{inv['attempt']}"
    return re.sub(r"[^A-Za-z0-9 ._-]", "-", raw)[:100]


def submit(api: Spark, body: dict, key: str, admission_wait: float, sleep=time.sleep) -> dict:
    """POST the application; wait out admission (429) and brief outages; fail on a refusal."""
    deadline = time.monotonic() + admission_wait
    outages = 0
    while True:
        try:
            status, _, raw = api.call("POST", "/v1/applications", body, {"Idempotency-Key": key})
        except OSError as e:
            status, raw = 0, str(e).encode()
        if status in (200, 201):
            return json.loads(raw)
        if status == 429:
            if time.monotonic() >= deadline:
                raise Failed(f"booth-spark had no capacity for {admission_wait:g}s: {spark_error(status, raw)}")
            event("waiting", reason=spark_error(status, raw), retryIn=30)
            sleep(30)
            continue
        if status == 0 or status >= 500:
            outages += 1
            if outages > 3:
                raise Failed(f"could not submit to booth-spark: {spark_error(status, raw) if status else raw.decode()}")
            sleep(5 * outages)
            continue
        if status == 404:
            raise Failed("booth-spark is not installed in this workspace's Booth (the gateway has no /modules/spark)")
        raise Failed(f"booth-spark refused the application (HTTP {status}): {spark_error(status, raw)}")


class LogCopy:
    """Copies the driver log to stdout once, with booth-spark's log cursor (?from=, X-Log-Offset). An
    older booth-spark without the cursor gets its kept log copied once, when the run ends."""

    def __init__(self, api: Spark, app_id: str) -> None:
        self.api, self.app_id = api, app_id
        self.offset: int | None = 0
        self.partial = ""
        self.tail: list[str] = []  # recent lines, for the output marker

    def _emit(self, text: str) -> None:
        text = self.partial + text
        lines = text.split("\n")
        self.partial = lines.pop()  # an unfinished last line waits for the rest
        for line in lines:
            self._line(line.rstrip("\r"))

    def _line(self, line: str) -> None:
        self.tail = (self.tail + [line])[-500:]
        if not line.startswith(OUTPUT):
            print(line, flush=True)

    def poll(self) -> None:
        if self.offset is None:
            return
        status, headers, raw = self.api.call("GET", f"/v1/applications/{self.app_id}/logs?from={self.offset}")
        nxt = {k.lower(): v for k, v in headers.items()}.get("x-log-offset")
        if status != 200 or nxt is None:
            self.offset = None  # no cursor here: the whole kept log is copied at the end instead
            return
        self._emit(raw.decode("utf-8", errors="replace"))
        self.offset = int(nxt)

    def finish(self) -> None:
        if self.offset is not None:
            self.poll()
        if self.offset is None:
            status, _, raw = self.api.call("GET", f"/v1/applications/{self.app_id}/logs?tail=10000")
            if status == 200:
                self._emit(raw.decode("utf-8", errors="replace") + "\n")
            elif status == 410:
                print("(booth-spark has already cleared this run's log)", flush=True)
        if self.partial:
            self._line(self.partial)
            self.partial = ""

    def output(self) -> dict | None:
        """The marker line's ``{"output": ...}`` (with ``"skipped"`` if the task called ctx.skip), or None."""
        for line in reversed(self.tail):
            if line.startswith(OUTPUT):
                return json.loads(base64.b64decode(line[len(OUTPUT) :]))
        return None


def run(workdir: str, result_path: str, sleep=time.sleep) -> None:
    with open(os.path.join(workdir, "invocation.json"), encoding="utf-8") as f:
        inv = json.load(f)
    spark = inv["spark"]
    with open(os.path.join(workdir, "task.py"), encoding="utf-8") as f:
        source = f.read()
    token_file = os.environ.get("BOOTH_TOKEN_FILE")
    if not token_file:
        raise Failed("a Spark task needs the run's token, and this pod was given none")
    api = Spark(spark["url"], spark["workspace"], token_file)
    body = {
        "name": app_name(inv),
        "main": {"inlinePython": build_code(source, inv, spark, _read_modules(workdir))},
        "args": list(spark.get("args") or []),
        "conf": dict(spark.get("conf") or {}),
        "maxDuration": f"{int(inv['timeoutSeconds'])}s",
    }
    resources = _drop_empty(spark.get("resources") or {})
    if resources:
        body["resources"] = resources
    data = spark.get("dataAccess") or {}
    if data.get("database") or data.get("lakehouse") or data.get("storage"):
        body["dataAccess"] = data
    key = f"{inv['runId']}/{inv['taskKey']}/{inv['attempt']}"
    app = submit(api, body, key, float(spark.get("admissionWaitSeconds", 900)), sleep)
    app_id = str(app["id"])
    event("submitted", id=app_id, state=app.get("state", "pending"))
    logs = LogCopy(api, app_id)
    state = app.get("state", "pending")
    poll = float(spark.get("pollSeconds", 5))
    while state not in TERMINAL:
        sleep(poll)
        logs.poll()
        try:
            status, _, raw = api.call("GET", f"/v1/applications/{app_id}")
        except OSError:
            continue  # a blip; the backend's timeout and Spark's maxDuration bound the wait
        if status != 200:
            continue
        cur = json.loads(raw)
        if cur.get("state") != state:
            state = cur.get("state")
            event("state", id=app_id, state=state, reason=cur.get("reason") or "")
        app = cur
    logs.finish()
    reason = app.get("reason") or ""
    if state == "failed":
        raise Failed(f"spark application {app_id} failed" + (f": {reason}" if reason else ""))
    if state == "stopped":
        raise Failed(f"spark application {app_id} was stopped" + (f": {reason}" if reason else ""))
    result = logs.output()
    if result is None:
        raise Failed(f"spark application {app_id} succeeded, but its output line wasn't found in its log")
    with open(result_path, "w", encoding="utf-8") as f:
        json.dump(result, f)


def _read_modules(workdir: str) -> dict[str, str]:
    """The shared modules the runner wrote beside task.py (modules/<name>.py), to send along inline."""
    d = os.path.join(workdir, "modules")
    if not os.path.isdir(d):
        return {}
    out = {}
    for f in sorted(os.listdir(d)):
        if f.endswith(".py"):
            with open(os.path.join(d, f), encoding="utf-8") as fh:
                out[f[:-3]] = fh.read()
    return out


def _drop_empty(d: dict) -> dict:
    out = {}
    for k, v in d.items():
        if isinstance(v, dict):
            v = _drop_empty(v)
        if v not in (None, {}, []):
            out[k] = v
    return out


def main() -> int:
    workdir, result_path = sys.argv[1], sys.argv[2]
    try:
        run(workdir, result_path)
        return 0
    except Failed as e:
        message = str(e)
    except Exception as e:  # noqa: BLE001 - a client bug still fails the task with a reason
        message = f"the Spark client failed: {e.__class__.__name__}: {e}"
    print(message, file=sys.stderr, flush=True)
    with open(os.path.join(workdir, "failure.txt"), "w", encoding="utf-8") as f:
        f.write(message)
    return 1


if __name__ == "__main__":
    sys.exit(main())
